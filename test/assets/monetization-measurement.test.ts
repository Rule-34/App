import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const source = (path: string) => readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8')

describe('monetization measurement', () => {
  it('tracks revenue actions without high-volume or acquisition-overwriting signals', () => {
    const promotedContent = source('app/components/pages/posts/PromotedContent.vue')
    const aiReferral = source('app/components/pages/posts/post/PostChatWithAi.vue')
    const premium = source('app/pages/premium/index.vue')
    const premiumOriginal = source('app/components/pages/premium/PremiumLandingOriginal.vue')
    const premiumOffer = source('app/components/pages/premium/PremiumOfferLanding.vue')
    const experiments = source('app/composables/useExperiments.ts')
    const matomo = source('app/plugins/040.matomo.client.ts')
    const matomoClient = source('app/assets/js/matomo.ts')

    expect(source('app/assets/js/promotions.ts')).not.toContain('utm_source=internal')
    expect(promotedContent).toContain("'Promoted Content'")
    expect(promotedContent).not.toContain('sessionStorage')
    expect(promotedContent).not.toContain('vIntersectionObserver')
    expect(promotedContent).not.toContain("'Impression'")
    expect(aiReferral).not.toContain('trackEvent')
    expect(premiumOriginal).not.toContain("'Checkout Outbound'")
    expect(premiumOriginal).toContain('trackPremiumPlanClick(interval.key)')
    expect(premiumOffer).toContain('trackPremiumPlanClick(interval.key)')
    expect(premiumOriginal).toContain('id="pricing"')
    expect(premium).toContain('<PremiumLandingOriginal')
    expect(premium).toContain('<PremiumOfferLanding')
    expect(premiumOffer).toContain('checkoutPrice: 59.64')
    expect(premiumOffer).toContain('selectedPaymentInterval.checkoutPrice')
    expect(experiments).not.toContain('sessionStorage')
    expect(experiments).not.toContain('YearlyFocus')
    expect(matomoClient).toContain("['original', 'OfferFirst', 'VisualFirst']")
    expect(matomoClient).toContain('PremiumLandingV2')
    expect(matomoClient).not.toContain('YearlyFocus')
    expect(premiumOffer).not.toContain('YearlyFocus')
    expect(premium).toContain('data-testid="premium-visual-hero"')
    expect(premium).toContain('fetchpriority="high"')
    expect(premium).toContain('loading="eager"')
    expect(premium).toContain('data-premium-landing')
    expect(premium).toContain('variant="OfferFirst"')
    expect(premium).toContain('variant="VisualFirst"')
    expect(matomoClient).toContain("['enableLinkTracking']")
    expect(matomoClient.match(/\['enableLinkTracking'\]/g)).toHaveLength(1)
    expect(matomo).toContain('onNuxtReady(() =>')
    expect(matomo).toContain('hasInteracted')
    expect(matomo).toContain('isPremiumRoute')
    expect(matomo).toContain('isPremiumRoute(router.currentRoute.value.path)')
    expect(matomo.indexOf('isPremiumRoute(router.currentRoute.value.path)')).toBeLessThan(
      matomo.indexOf('hasInteracted')
    )
    expect(matomoClient).toContain('new Experiment(')
    expect(matomoClient).toContain('await activatePremiumLandingExperiment(target)')
    expect(matomoClient.indexOf('await activatePremiumLandingExperiment(target)')).toBeLessThan(
      matomoClient.indexOf("['trackPageView']")
    )
    expect(matomoClient).toContain("['trackEvent', 'Premium', 'Plan Click', intervalKey]")
    expect(source('app/pages/premium/dashboard.vue')).toContain('trackPremiumSubscribed(')
    expect(source('app/components/pages/home/Newsletter.vue')).not.toContain("'Newsletter', 'Submit'")
  })
})
